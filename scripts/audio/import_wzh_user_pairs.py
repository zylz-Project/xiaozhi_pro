def ogg_duration_ms(data):
    offset = 0
    granule = 0
    pre_skip = None
    while offset < len(data):
        assert data[offset:offset+4] == b'OggS', 'invalid OGG page'
        segments = data[offset+26]
        table = data[offset+27:offset+27+segments]
        size = sum(table)
        start = offset+27+segments
        payload = data[start:start+size]
        assert len(payload) == size
        if payload.startswith(b'OpusHead'):
            assert payload[9] == 1, 'only mono Opus is supported'
            pre_skip = struct.unpack_from('<H', payload, 10)[0]
        value = struct.unpack_from('<Q', data, offset+6)[0]
        if value != 0xffffffffffffffff:
            granule = max(granule, value)
        offset = start+size
    assert pre_skip is not None and granule > pre_skip
    return (granule-pre_skip)*1000//48000


def load_pair(path, product, axes):
    with zipfile.ZipFile(path) as archive:
        info = archive.infolist()
        assert len(info) <= 8 and sum(i.file_size for i in info) <= 8*1024*1024
        assert all(i.file_size <= 4*1024*1024 for i in info)
        assert archive.testzip() is None
        manifest = json.loads(archive.read('manifest.json'))
        assert manifest['product'] == product
        motion_data = archive.read(manifest['motion'])
        audio = archive.read(manifest['audio'])
        for field, data in [('motion', motion_data), ('audio', audio)]:
            assert hashlib.sha256(data).hexdigest() == manifest[field+'_sha256'], path
        assert len(audio) == manifest['audio_size']
        motion = json.loads(motion_data)
        assert motion['flags'] == 0, 'import preserves exact user-authored playback'
        rows = motion['keyframes']
        assert len(rows) == motion['frame_count'] and 2 <= len(rows) <= 64
        assert sum(row[0] for row in rows) == motion['duration_ms'] <= 30000
        sound = motion['sound']
        assert 0 < len(sound.encode()) < 64 and '/' not in sound and '\\' not in sound
        if axes == 3:
            expected = ['head', 'left_arm', 'right_arm'] if product == 'crawling-panda' else ['head', 'tail_lr', 'tail_ud']
            assert motion['schema_version'] == 2 and motion['axis_order'] == expected
            assert motion['coordinate_space'] == 'physical_degrees'
        else:
            # Verified against dinosaur_action (1)'s release exporter and pipeline:
            # ch0=IO17 tilt, ch1=IO16 lean, ch2=IO15 head, ch3=IO8, ch4=IO18.
            # Schema 1 stores only tail-UD in legacy coordinates, 0=up.
            assert motion['schema_version'] == 1
        frames = []
        clamped = 0
        for row in rows:
            assert len(row) == axes+2 and all(type(v) is int for v in row)
            assert 20 <= row[0] <= 10000 and row[-1] in [0, 1, 2]
            values = row[1:-1]
            if axes == 5:
                assert 0 <= values[3] <= 125
                values[3] = 180-values[3]
            assert all(0 <= value <= 180 for value in values)
            low = [0, 0, 0, 55, 0] if axes == 5 else [8, 6, 10] if product == 'tail-wagging-panda' else [8, 8, 8]
            high = [180]*5 if axes == 5 else [172, 174, 178] if product == 'tail-wagging-panda' else [172]*3
            physical = [max(lo, min(hi, value)) for value, lo, hi in zip(values, low, high)]
            clamped += sum(a != b for a, b in zip(values, physical))
            frames.append([row[0], physical+[0]*(5-axes), row[-1]])
        return manifest, motion, audio, frames, clamped


def generate():
    report = []
    for board, product, source, axes in PRODUCTS:
        lines = ['// Generated by scripts/audio/import_wzh_user_pairs.py; validated user assets.',
                 '#include "wzh_user_pairs.h"', 'namespace wzh_user_assets {']
        entries = []
        archives = sorted(p for p in Path(source).rglob('*') if p.is_file() and zipfile.is_zipfile(p))
        for i, path in enumerate(archives):
            manifest, motion, audio, frames, clamped = load_pair(path, product, axes)
            audio_ms = ogg_duration_ms(audio)
            lines.append(f'inline constexpr uint8_t kAudio{i}[] = {{')
            for at in range(0, len(audio), 24):
                lines.append('    '+','.join(f'0x{x:02x}' for x in audio[at:at+24])+',')
            lines.append('};')
            lines.append(f'inline constexpr wzh::UserPairFrame kFrames{i}[] = {{')
            lines += ['    {'+str(dt)+', {'+','.join(map(str, pose))+'}, '+str(ease)+'},' for dt, pose, ease in frames]
            lines.append('};')
            # Analyse the actual paired recording, not an older Flash file with
            # a similar name. This runs on the workstation, never in audio tasks.
            pcm = array.array('h', subprocess.run([
                'ffmpeg', '-v', 'error', '-i', 'pipe:0', '-ar', '8000',
                '-ac', '1', '-f', 's16le', 'pipe:1'], input=audio,
                capture_output=True, check=True).stdout)
            rms = [math.sqrt(sum(v*v for v in pcm[at:at+800])/len(pcm[at:at+800]))
                   for at in range(0, len(pcm), 800)]
            assert rms and abs(len(pcm)/8-audio_ms) < 100
            reference = max(sorted(rms)[int((len(rms)-1)*.95)], 1)
            levels = [round(min(1, v/reference)**.65*255) for v in rms]
            sound_kind = kind(motion['sound'], 'animal')
            if axes == 5 and any(s in motion['sound'] for s in ['长鸣', '哀鸣']):
                sound_kind = 'Roar' if '长鸣' in motion['sound'] else 'Affection'
            lines.append(f'inline constexpr uint8_t kEnvelope{i}[] = {{'+','.join(map(str, levels))+'};')
            lines.append(f'inline constexpr wzh::SoundScore kScore{i} = {{'+
                json.dumps(motion['sound'], ensure_ascii=False)+f', wzh::SoundKind::k{sound_kind}, '+
                f'{audio_ms}, 0x{manifest["audio_sha256"][:8]}U, kEnvelope{i}, sizeof(kEnvelope{i})'+'};')
            alias = ALIASES.get(motion['name'], '')
            entries.append('    {'+json.dumps(motion['sound'], ensure_ascii=False)+', '+json.dumps(alias, ensure_ascii=False)+f', kAudio{i}, sizeof(kAudio{i}), {audio_ms}, kFrames{i}, {len(frames)}, {motion["duration_ms"]}, {axes}, &kScore{i}'+'},')
            report.append(dict(board=board, source=str(path), name=motion['sound'], audio_ms=audio_ms,
                motion_ms=motion['duration_ms'], frames=len(frames), audio_size=len(audio),
                audio_sha256=manifest['audio_sha256'], motion_sha256=manifest['motion_sha256'],
                mechanical_limit_clamps=clamped, coordinate_conversion='legacy tail-UD only' if axes == 5 else 'physical degrees'))
        assert 0 < len(entries) <= 32
        lines += ['inline constexpr wzh::UserPair kPairs[] = {']+entries+['};', '}  // namespace wzh_user_assets', '']
        target = ROOT/'main/boards'/board/'wzh_user_pairs_catalog.inc'
        target.write_text('\n'.join(lines))
    target = ROOT/'docs/wzh_user_pairs_2026-10-20.json'
    target.write_text(json.dumps(report, ensure_ascii=False, indent=2)+'\n')
    print(f'{len(report)} paired archives validated and imported')


if __name__ == '__main__':
    generate()

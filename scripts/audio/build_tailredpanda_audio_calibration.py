#!/usr/bin/env python3
"""Generate gain metadata for the exact existing tail-panda/prompt assets.

Original Opus payloads, motion frames and generated pair catalogs stay untouched.
"""
import json
import math
from pathlib import Path
import re

from prepare_product_audio import measure, choose_gain, fingerprint

ROOT = Path(__file__).resolve().parents[2]


def main():
    sources=[]
    for file in sorted((ROOT/'main/assets/locales/zh-CN').glob('*.ogg')):
        sources.append((file.name, file.read_bytes()))
    catalog=(ROOT/'main/boards/wzh_tailRedPanda/wzh_user_pairs_catalog.inc').read_text()
    for number,body in re.findall(r'inline constexpr uint8_t kAudio(\d+)\[\] = \{(.*?)\};', catalog,re.S):
        sources.append(('paired-'+number,bytes(int(v,16) for v in re.findall(r'0x([0-9a-fA-F]{2})',body))))
    assert sources, 'No bundled sources found'
    entries=[];report=[];seen={}
    for name,data in sources:
        key=(fingerprint(data),len(data))
        if key in seen:
            assert seen[key]==data, 'Fingerprint collision'
            continue
        seen[key]=data
        info=measure(data);gain=choose_gain(info, protected_playback=True)
        entries.append((key[0],key[1],gain))
        report.append({'source':name,'bytes':len(data),'fingerprint':f'{key[0]:016x}',
                       'gain_q8':gain,'gain_db':gain/256,
                       'measurement':{k:v if math.isfinite(v) else None for k,v in info.items()}})
    lines=['// Generated by scripts/audio/build_tailredpanda_audio_calibration.py. Do not hand edit.',
           '#include "audio_source_gain.h"','namespace tail_audio_calibration {',
           'struct Entry { uint64_t fingerprint; size_t bytes; int16_t gain_q8; };',
           'inline constexpr Entry kEntries[] = {']
    lines += [f'    {{UINT64_C(0x{key:016x}), {size}, {gain}}},' for key,size,gain in entries]
    lines += ['};','inline int16_t Find(const uint8_t* data, size_t size) {',
              '    if (data == nullptr || size == 0) return 0;',
              '    bool known_size = false;',
              '    for (const auto& entry : kEntries) known_size = known_size || entry.bytes == size;',
              '    if (!known_size) return 0;',
              '    const uint64_t key = AudioSourceFingerprint(data, size);',
              '    for (const auto& entry : kEntries)',
              '        if (entry.bytes == size && entry.fingerprint == key) return entry.gain_q8;',
              '    return 0;', '}', '}  // namespace tail_audio_calibration', '']
    (ROOT/'main/boards/wzh_tailRedPanda/audio_calibration.inc').write_text('\n'.join(lines))
    (ROOT/'docs/wzh_tailredpanda_audio_calibration_2026-11-04.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps({'sources':len(entries),'gain_db_min':min(g for _,_,g in entries)/256,
                      'gain_db_max':max(g for _,_,g in entries)/256},indent=2))


if __name__=='__main__':main()

#ifndef _WZH_DINOSAUR_CONFIG_H_
#define _WZH_DINOSAUR_CONFIG_H_

#include <driver/gpio.h>
#include <driver/ledc.h>
#include <driver/spi_master.h>
#include <esp_adc/adc_oneshot.h>

// ES8311 同时服务于在线语音和离线本地声音。二者共用 XiaoZhi AudioService，
// 不允许离线模块再次安装 I2S 驱动。
#define AUDIO_INPUT_SAMPLE_RATE 24000
#define AUDIO_OUTPUT_SAMPLE_RATE 24000
#define AUDIO_I2S_GPIO_MCLK GPIO_NUM_NC
#define AUDIO_I2S_GPIO_WS GPIO_NUM_13
#define AUDIO_I2S_GPIO_BCLK GPIO_NUM_48
#define AUDIO_I2S_GPIO_DOUT GPIO_NUM_46
#define AUDIO_I2S_GPIO_DIN GPIO_NUM_14
#define AUDIO_CODEC_I2C_SDA_PIN GPIO_NUM_2
#define AUDIO_CODEC_I2C_SCL_PIN GPIO_NUM_38
#define AUDIO_CODEC_PA_PIN GPIO_NUM_NC
#define AUDIO_CODEC_ES8311_ADDR ES8311_CODEC_DEFAULT_ADDR

#define BOOT_BUTTON_GPIO GPIO_NUM_0

// 电源锁存、模拟电源键和电池分压。
// POWER_CTRL_GPIO 拉高维持整机供电，长按电源键后拉低完成关机。
#define POWER_CTRL_GPIO GPIO_NUM_7
#define POWER_BUTTON_GPIO GPIO_NUM_6
#define POWER_BUTTON_ADC_CHANNEL ADC_CHANNEL_5
#define POWER_BUTTON_ADC_THRESHOLD 1241
#define POWER_LONG_PRESS_MS 1500
#define POWER_DEBOUNCE_MS 50
#define POWER_POLL_MS 20
#define BATTERY_ADC_CHANNEL ADC_CHANNEL_2
#define BATTERY_DIVIDER_RATIO 2
#define BATTERY_READ_TICKS 250  // 每 5s（250 * 20ms）采样一次
#define BATTERY_EMPTY_VOLTAGE_MV 3200
#define BATTERY_FULL_VOLTAGE_MV 4200

// 五路恐龙舵机。下面的默认角度只代表软件中位，不保证适合所有装配方向；
// 尤其是尾巴上下轴，先用较小范围完成真机限位校准。
#define SERVO_POWER_GPIO GPIO_NUM_4
#define SERVO_HEAD_TURN_GPIO GPIO_NUM_15
#define SERVO_NECK_LEAN_GPIO GPIO_NUM_16
#define SERVO_NECK_TILT_GPIO GPIO_NUM_17
#define SERVO_TAIL_LR_GPIO GPIO_NUM_18
#define SERVO_TAIL_UD_GPIO GPIO_NUM_8
#define SERVO_NECK_TILT_DEFAULT 70
#define SERVO_NECK_LEAN_DEFAULT 90
#define SERVO_HEAD_TURN_DEFAULT 90
#define SERVO_TAIL_UD_DEFAULT 90
#define SERVO_TAIL_LR_DEFAULT 90
#define SERVO_TAIL_UD_MIN 55
#define SERVO_TAIL_UD_MAX 180
#define SERVO_TIMER LEDC_TIMER_0
#define SERVO_FREQ_HZ 50
#define SERVO_DUTY_RES LEDC_TIMER_13_BIT

// W25Q256 中保存已经烧录好的默认声音，运行时只读。
// 前 4 KiB 存放 PNDA TOC，音频数据从 DINO_FLASH_DATA_START 开始。
#define DINO_FLASH_HOST SPI2_HOST
#define DINO_FLASH_CS_PIN GPIO_NUM_10
#define DINO_FLASH_CLK_PIN GPIO_NUM_9
#define DINO_FLASH_MOSI_PIN GPIO_NUM_47
#define DINO_FLASH_MISO_PIN GPIO_NUM_21
#define DINO_FLASH_SIZE (32U * 1024U * 1024U)
#define DINO_FLASH_DATA_START 4096U

// 自定义配网热点前缀：开机没有已保存 WiFi 时，开启 "Dino-XXXX" 热点配网。
#define PANDA_AP_PREFIX "Dino"

#endif  // _WZH_DINOSAUR_CONFIG_H_
